import * as React from "react";

import { cn } from "@/lib/utils";

/**
 * O acabamento de vidro NÃO mora aqui.
 *
 * A primeira tentativa foi embutir o vidro neste componente — e isso vazou para
 * a tela de login, que usa o mesmo `Card`. O arquivo `routes/auth.tsx` não tinha
 * sido editado, mas o login passou a renderizar com um degradê branco que não
 * era dele. "Não editei o arquivo" não é o mesmo que "não alterei a tela".
 *
 * O acabamento vive em `styles.css`, escopado em `.af-app [data-slot="card"]`.
 * `.af-app` fica no shell autenticado, então o login não recebe nada.
 * O `data-slot` existe só para dar esse gancho — não muda estilo por si.
 */
